"""Database-level rules on the users table: they hold even if application code has a bug."""

import pytest
from sqlalchemy import text
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from app.domain.enums import UserRole
from tests.conftest import MakeUser

INSERT = text(
    "INSERT INTO users (email, phone, full_name, password_hash, role, is_super_admin) "
    "VALUES (:email, :phone, 'X Y', 'hash', :role, :super)"
)


def _insert(db: Session, **values: object) -> None:
    params = {"email": "a@example.com", "phone": "+923000000999", "role": "provider", "super": False}
    params.update(values)
    db.execute(INSERT, params)
    db.commit()


def test_email_unique_ignoring_case(db_session: Session, make_user: MakeUser) -> None:
    make_user(email="ali@example.com")
    with pytest.raises(IntegrityError, match="uq_users_email"):
        _insert(db_session, email="ALI@EXAMPLE.COM")


def test_phone_unique(db_session: Session, make_user: MakeUser) -> None:
    make_user(phone="+923000000999")
    with pytest.raises(IntegrityError, match="uq_users_phone"):
        _insert(db_session, email="b@example.com")


def test_unknown_role_rejected_by_check_constraint(db_session: Session) -> None:
    with pytest.raises(IntegrityError, match="ck_users_user_role"):
        _insert(db_session, role="hacker")


def test_only_admins_can_be_super_admins(db_session: Session) -> None:
    with pytest.raises(IntegrityError, match="ck_users_super_admin_is_admin"):
        _insert(db_session, role=UserRole.PROVIDER.value, super=True)


def test_defaults_for_new_user(db_session: Session) -> None:
    _insert(db_session)
    row = db_session.execute(
        text("SELECT account_status, verification_status, token_version, is_super_admin, id FROM users")
    ).one()
    assert row[:4] == ("active", "not_submitted", 0, False)
    assert len(str(row.id)) == 36  # UUID generated by PostgreSQL
